	public function message()
	{
		// Генерация случайного сообщения
		$text = $this->randomElement($this->messages);

		// Генерация случайной даты (например, за последние 30 дней)
		$faker = Factory::create();
		$date = $faker->dateTimeBetween('-30 days', 'now');

		// Форматирование даты в "14 ноября в 14:28"
		$formattedDate = $this->formatRussianDate($date);

		// Генерация случайного статуса isChange (true или false)
		$isMyMessage = $faker->boolean();

		// Возвращаем массив с текстом, датой и статусом
		return [
			'text' => $text,
			'date' => $formattedDate,
			'isMyMessage' => $isMyMessage,
		];
	}

	/**
	 * Форматирует дату в формат "14 ноября в 14:28".
	 *
	 * @param \DateTime $date
	 * @return string
	 */
	private function formatRussianDate(\DateTime $date): string
	{
		// Массив с названиями месяцев на русском языке
		$months = [
			1 => 'января', 2 => 'февраля', 3 => 'марта', 4 => 'апреля',
			5 => 'мая', 6 => 'июня', 7 => 'июля', 8 => 'августа',
			9 => 'сентября', 10 => 'октября', 11 => 'ноября', 12 => 'декабря',
		];

		// Получаем день, месяц и время
		$day = $date->format('j'); // День без ведущего нуля
		$month = $months[(int) $date->format('n')]; // Месяц на русском
		$time = $date->format('H:i'); // Время в формате 14:28

		// Возвращаем отформатированную строку
		return "{$day} {$month} в {$time}";
	}
